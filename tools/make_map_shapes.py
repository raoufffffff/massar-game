# Per-place hover glow, lock tint and click mask for the city map.
# usage: python tools/make_map_shapes.py <game_dir> <masks_dir>   (masks from trace_map.py)
import sys, os, json, cv2, numpy as np
game, masks = sys.argv[1], sys.argv[2]
k = 1920 / 2576.0                      # map (2576 wide) -> game screen (1920 wide)
out = os.path.join(game, "images", "map"); os.makedirs(out, exist_ok=True)
polys = json.load(open(os.path.join(os.path.dirname(__file__), "map_polys.json")))
boxes = json.load(open(os.path.join(os.path.dirname(__file__), "map_boxes.json")))
H, W = 1438, 2576
shapes = {}
def get_mask(pid):
    if pid in polys:
        m = np.zeros((H, W), np.uint8); cv2.fillPoly(m, [np.array(polys[pid], np.int32)], 255); return m
    return cv2.imread(os.path.join(masks, "m_%s.png" % pid), 0)
ids = list(boxes.keys()) + list(polys.keys())
for pid in ids:
    m = get_mask(pid)
    m = cv2.resize(m, (int(W * k), int(H * k)), interpolation=cv2.INTER_AREA)
    m = np.where(m > 127, 255, 0).astype(np.uint8)
    ys, xs = np.where(m > 0)
    mg = 30
    x0, y0 = max(0, xs.min() - mg), max(0, ys.min() - mg)
    x1, y1 = min(m.shape[1], xs.max() + mg), min(m.shape[0], ys.max() + mg)
    c = m[y0:y1, x0:x1]
    h, w = c.shape
    # hover: soft warm glow around the outline + light fill + thin white edge
    dil = cv2.dilate(c, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (19, 19)))
    glow = cv2.GaussianBlur(dil, (0, 0), 6).astype(np.float32) / 255.0
    edge = cv2.dilate(c, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (5, 5))) - c
    hov = np.zeros((h, w, 4), np.float32)
    hov[..., :3] = (255, 236, 150)[::-1]          # BGR
    hov[..., 3] = glow * 215
    fill = (c.astype(np.float32) / 255.0)
    for ch in range(3):
        hov[..., ch] = hov[..., ch] * (1 - fill * 0.2) + 255 * fill * 0.2
    hov[..., 3] = np.maximum(hov[..., 3], fill * 60)
    e = edge.astype(np.float32) / 255.0
    for ch in range(3):
        hov[..., ch] = hov[..., ch] * (1 - e) + 255 * e
    hov[..., 3] = np.maximum(hov[..., 3], e * 255)
    cv2.imwrite(os.path.join(out, "%s_hover.png" % pid), hov.clip(0, 255).astype(np.uint8))
    idle = np.zeros((h, w, 4), np.uint8); idle[..., 3] = np.where(c > 0, 4, 0)   # click mask, ~invisible
    cv2.imwrite(os.path.join(out, "%s_idle.png" % pid), idle)
    lock = np.zeros((h, w, 4), np.uint8); lock[..., 3] = np.where(c > 0, 105, 0)  # dark tint for locked places
    cv2.imwrite(os.path.join(out, "%s_lock.png" % pid), lock)
    shapes[pid] = (int(x0), int(y0), int(w), int(h))
with open(os.path.join(game, "map_shapes.py"), "w") as f:
    f.write("# -*- coding: utf-8 -*-\n# Generated by tools/make_map_shapes.py: bounding boxes (game pixels, before the map's top offset)\n")
    f.write("SHAPES = %r\n" % shapes)
print(len(shapes), "shapes")
