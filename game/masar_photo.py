# -*- coding: utf-8 -*-
"""Masar photography mini-game: pure logic (testable outside Ren'Py).

The light level (0-100) keeps fluctuating. The score of a shot is the light level
at the moment of capture = the "match" percentage. Above 50 the photo helps the
page (views, subscribers, donations), below 50 it hurts.
"""
import math
import random


class LightWave(object):
    """Fluctuating light: a slow swell + medium and fast flicker (clouds, wind)."""

    def __init__(self, seed=0, speed=1.0):
        rng = random.Random(seed)
        self.speed = speed
        two_pi = 2 * math.pi
        # (weight, frequency in Hz, phase). Weights sum to 1 so the value stays in 0..100.
        self.comps = [
            (0.55, rng.uniform(0.35, 0.50), rng.uniform(0, two_pi)),
            (0.30, rng.uniform(0.90, 1.30), rng.uniform(0, two_pi)),
            (0.15, rng.uniform(1.80, 2.60), rng.uniform(0, two_pi)),
        ]

    def value(self, t):
        s = sum(w * math.sin(2 * math.pi * f * t * self.speed + p) for w, f, p in self.comps)
        return 50.0 + 50.0 * s


# (minimum score, label, views, subscribers change, donations). Placeholder numbers: tune later.
TIERS = [
    (0,  "Ruined shot", 40,    -20,   0),
    (25, "Poor shot",   120,   -8,    0),
    (50, "Decent",      400,   5,     0),
    (65, "Good",        1500,  20,    10),
    (80, "Great",       5000,  60,    40),
    (95, "Perfect",     15000, 150,   150),
]


def outcome(score):
    """Result of a photo with the given score (0-100)."""
    best = TIERS[0]
    for t in TIERS:
        if score >= t[0]:
            best = t
    return {"label": best[1], "views": best[2], "subs": best[3], "donations": best[4],
            "positive": score >= 50}


def session_result(scores, mode="best"):
    """Final score of a session of several shots."""
    if not scores:
        return 0
    if mode == "average":
        return int(round(sum(scores) / float(len(scores))))
    return max(scores)


# =====================================================================
#  The camera: lens window, real zoom/pan, focus, live scenes, expression timeline
# =====================================================================
import math as _m

WORLD_W, WORLD_H = 1920, 1080           # the scene (background + Ana): 1920 wide, or wider in a panoramic room
BASE_W = 1920                           # width of an ordinary (non-panoramic) room
WIN_X, WIN_Y, WIN_W, WIN_H = 330, 80, 1260, 820   # the lens window on screen
BASE = WIN_H / float(WORLD_H)           # world -> window scale at zoom 1
ZOOM_MIN, ZOOM_MAX = 1.0, 2.6
ANA_W, ANA_H = 800, 1080                # Ana's picture as shown in the scene (world pixels)
IMG_ZOOM = 0.5                          # camera pictures are 1600x2160, shown at half size = sharp zoom
VK = 1.0                                # ROI units -> world pixels
ANA_TOP = 0                             # world y of the picture's top edge
LOOP_LENGTH = 10.0


# ---------------------------------------------------------------------
#  Scenes. A scene = a place + the activity Ana is doing + her pictures. The game builds the
#  "video" from these pictures at run time: expressions are blended on a generated timeline.
#  ROIs are rectangles (x, y, w, h) in the 800x1080 picture; zoom = the ideal zoom of the shot.
# ---------------------------------------------------------------------
import poses_data      # generated by tools/add_pose.py from poses/*.json
PARTS = poses_data.PARTS
EXPR_NAMES = {"neutral": "calm", "smile": "smiling", "shy": "shy"}

SCENES = poses_data.SCENES


def scene_files(scene_id):
    """Every picture a scene needs (for preloading)."""
    sc = SCENES[scene_id]
    files = list(sc["images"].values())
    for kind in LAYERS.get(sc.get("face"), {}).values():
        files += [v[2] for v in kind.values()]
    return files


def poses_here(place, room, available=None):
    """[(pose, title)] of the photo scenes that exist in this room (and whose picture is installed)."""
    out = []
    for sc in SCENES.values():
        if sc["place"] == place and sc["room"] == room and (available is None or sc["pose"] in available):
            out.append((sc["pose"], sc["title"]))
    return out


def scene_for(pose, place, room):
    """Id of the photo scene that matches what Ana is doing here, or None."""
    for sid, sc in SCENES.items():
        if sc["pose"] == pose and sc["place"] == place and sc["room"] == room:
            return sid
    return None


# ---- expression timeline ------------------------------------------------
# Face keyframes [(second, label)] with label neutral / smile / shy; between two keyframes the weights
# blend linearly. Blinks are separate: a list of times, eyes shut for ~0.17 s ("closed" ruins a shot).
# Both are generated per shot from her mood. The game draws: the neutral picture, then the mouth and
# eyes patches of the current expression, then the closed-eyes patch while she blinks.
try:
    from face_layers import LAYERS
except Exception:       # run outside the game folder
    LAYERS = {}
BLINK_IN, BLINK_OUT = 0.07, 0.10
MOOD_WEIGHTS = {
    "neutral":   {"neutral": 0.62, "smile": 0.33, "shy": 0.05},
    "smile":     {"neutral": 0.30, "smile": 0.65, "shy": 0.05},
    "shy":       {"neutral": 0.25, "smile": 0.25, "shy": 0.50},
    "sad":       {"neutral": 0.55, "smile": 0.05, "shy": 0.40},
    "angry":     {"neutral": 0.80, "smile": 0.05, "shy": 0.15},
    "surprised": {"neutral": 0.40, "smile": 0.40, "shy": 0.20},
}


def _pick(rng, weights, avoid=None):
    items = [(k, v) for k, v in weights.items() if k != avoid]
    total = sum(v for _, v in items)
    r = rng.random() * total
    for k, v in items:
        r -= v
        if r <= 0:
            return k
    return items[-1][0]


def make_timeline(rng, mood="neutral", must=None, length=LOOP_LENGTH):
    """Generate her expression over one loop: (face keyframes, blink times). 'must' = an expression
    guaranteed to appear."""
    w = MOOD_WEIGHTS.get(mood, MOOD_WEIGHTS["neutral"])
    segs = []                       # (label, hold seconds)
    t = 0.0
    cur = _pick(rng, w)
    while t + 1.5 <= length - 0.4:
        hold = min(rng.uniform(1.5, 2.6), length - 0.4 - t)
        segs.append((cur, hold))
        t += hold + 0.4
        cur = _pick(rng, w, avoid=cur)
    if must and must not in [x[0] for x in segs]:
        segs[rng.randrange(len(segs))] = (must, 1.6)
    # base keyframes: hold each segment, ramp 0.4 s into the next; loop back to the first label
    keys = []
    t = 0.0
    for lab, hold in segs:
        keys.append((round(t, 3), lab))
        keys.append((round(t + hold, 3), lab))
        t += hold + 0.4
    keys.append((length, keys[0][1]))
    blinks = []
    tb = rng.uniform(1.0, 2.2)
    while tb < length - 0.6:
        blinks.append(round(tb, 3))
        tb += rng.uniform(2.6, 4.5)
    return keys, blinks


def expr_weights(t, keys, length=LOOP_LENGTH):
    """{label: weight 0..1} of her face (neutral / smile / shy) at time t of the loop."""
    t = t % length
    w = {"neutral": 0.0, "smile": 0.0, "shy": 0.0}
    for (t0, a), (t1, b) in zip(keys, keys[1:]):
        if t0 <= t <= t1:
            k = 0.0 if t1 == t0 else (t - t0) / float(t1 - t0)
            w[a] += 1.0 - k
            w[b] += k
            return w
    w[keys[-1][1]] = 1.0
    return w


def blink_weight(t, blinks, length=LOOP_LENGTH):
    """0..1: how closed her eyes are at time t (a quick close, a slightly slower open)."""
    t = t % length
    best = 0.0
    for tb in blinks:
        for off in (0.0, -length, length):
            d = t - (tb + off)
            if -BLINK_IN <= d <= 0:
                best = max(best, 1.0 + d / BLINK_IN)
            elif 0 < d <= BLINK_OUT:
                best = max(best, 1.0 - d / BLINK_OUT)
    return best


def layer_draws(shot, t):
    """What to draw for the lens or the target, bottom to top: [(path, world x, world y, alpha)]."""
    sc = SCENES[shot["scene"]]
    left = ana_left(shot["ax"])
    draws = [(sc["images"]["neutral"], left, ANA_TOP, 1.0)]
    lay = LAYERS.get(sc.get("face"), {})
    w = expr_weights(t, shot["tl"])
    for kind in ("mouth", "eyes"):
        for lab in ("smile", "shy"):
            if w[lab] > 0.004 and lab in lay.get(kind, {}):
                x, y, path = lay[kind][lab]
                draws.append((path, left + x * IMG_ZOOM, ANA_TOP + y * IMG_ZOOM, w[lab]))
    bw = blink_weight(t, shot["bl"])
    if bw > 0.004 and "closed" in lay.get("eyes", {}):
        x, y, path = lay["eyes"]["closed"]
        draws.append((path, left + x * IMG_ZOOM, ANA_TOP + y * IMG_ZOOM, bw))
    return draws


def expression_score(part, want, t, keys, blinks):
    """0..1: how well her expression at time t fits the request for this part."""
    w = expr_weights(t, keys)
    closed = blink_weight(t, blinks)
    ew = PARTS[part]["expr_w"]
    if ew <= 0:
        return max(0.0, 1.0 - closed)
    match = w.get(want, 0.0)
    return max(0.0, (1.0 - ew * (1.0 - match)) * (1.0 - closed))


def iou(a, b):
    ax, ay, aw, ah = a
    bx, by, bw, bh = b
    ix = max(0, min(ax + aw, bx + bw) - max(ax, bx))
    iy = max(0, min(ay + ah, by + bh) - max(ay, by))
    inter = ix * iy
    union = aw * ah + bw * bh - inter
    return inter / union if union else 0.0


def framing_quality(view, target):
    """0..1: how well a rectangle matches the requested one (IoU 0.75+ is perfect)."""
    return max(0.0, min(1.0, (iou(view, target) - 0.25) / 0.50))


# ---- camera geometry --------------------------------------------------
def clamp_zoom(z, zmax=None):
    return max(ZOOM_MIN, min(ZOOM_MAX if zmax is None else zmax, z))


def set_world(w):
    """Width of the room world the camera works in (1920, or the width of a panoramic room). Height is always 1080."""
    global WORLD_W
    WORLD_W = max(BASE_W, int(w))


def clamp_view(cx, cy, z):
    """Keep the view inside the world; (cx, cy) = world point at the window centre."""
    hw = WIN_W / 2.0 / (BASE * z)
    hh = WIN_H / 2.0 / (BASE * z)
    return (max(hw, min(WORLD_W - hw, cx)), max(hh, min(WORLD_H - hh, cy)))


def to_window(wx, wy, cx, cy, z):
    s = BASE * z
    return ((wx - cx) * s + WIN_W / 2.0, (wy - cy) * s + WIN_H / 2.0)


def ana_left(ax):
    """World x of Ana's picture left edge when her centre is at world x = ax."""
    return ax - ANA_W * VK / 2.0


def part_rect_window(part, ax, cx, cy, z):
    rx, ry, rw, rh = PARTS[part]["roi"]
    wx = ana_left(ax) + rx * VK
    wy = ANA_TOP + ry * VK
    x, y = to_window(wx, wy, cx, cy, z)
    s = BASE * z
    return (x, y, rw * VK * s, rh * VK * s)


def ideal_rect(part):
    """Where the part should sit in the window: centred, at the ideal zoom."""
    rx, ry, rw, rh = PARTS[part]["roi"]
    s = BASE * PARTS[part]["zoom"]
    w, h = rw * VK * s, rh * VK * s
    return ((WIN_W - w) / 2.0, (WIN_H - h) / 2.0, w, h)


def ideal_view(part, ax):
    """The perfect (cx, cy, zoom) for a shot - used by tests and the target pictures."""
    rx, ry, rw, rh = PARTS[part]["roi"]
    z = PARTS[part]["zoom"]
    cx = ana_left(ax) + (rx + rw / 2.0) * VK
    cy = ANA_TOP + (ry + rh / 2.0) * VK
    cx, cy = clamp_view(cx, cy, z)
    return cx, cy, z


def framing_score(part, ax, cx, cy, z):
    """Compared with the best view the world allows (at the edges a perfectly centred shot is impossible)."""
    icx, icy, iz = ideal_view(part, ax)
    return framing_quality(part_rect_window(part, ax, cx, cy, z), part_rect_window(part, ax, icx, icy, iz))


# ---- steadiness, portrait focus, hand shake --------------------------
def update_steady(steady, dt, moved, dzoom):
    """Moving or zooming shakes the camera (Ana turns blurry); holding still steadies it."""
    if moved < 1.0 and abs(dzoom) < 0.002:
        steady += 2.0 * dt
    else:
        steady -= moved / 220.0 + abs(dzoom) * 1.5
    return max(0.0, min(1.0, steady))


def update_bg_blur(bgb, held, dt):
    """Holding the focus key (portrait mode) blurs the background; releasing brings it back."""
    bgb += (2.5 if held else -3.0) * dt
    return max(0.0, min(1.0, bgb))


def blur_amount(level):
    """Blur in screen pixels for a 0..1 level (0 = sharp)."""
    return level * 9.0


def sway(t, z, steady):
    """Tiny hand shake in world pixels (smaller when steady)."""
    amp = 5.0 * _m.sqrt(z) * (1.0 - 0.5 * steady)
    s = BASE * z
    return (amp * (_m.sin(t * 1.7) + 0.5 * _m.sin(t * 3.1 + 1.0)) / s,
            amp * (_m.sin(t * 1.3 + 2.0) + 0.5 * _m.sin(t * 2.7)) / s)


def edge_push(mx, my, margin=110.0):
    """Mouse near an edge of the lens window pushes the view: (-1..1, -1..1)."""
    px, py = mx - WIN_X, my - WIN_Y
    if px < 0 or py < 0 or px > WIN_W or py > WIN_H:
        return (0.0, 0.0)
    vx = vy = 0.0
    if px < margin:
        vx = -(margin - px) / margin
    elif px > WIN_W - margin:
        vx = (px - (WIN_W - margin)) / margin
    if py < margin:
        vy = -(margin - py) / margin
    elif py > WIN_H - margin:
        vy = (py - (WIN_H - margin)) / margin
    return (vx, vy)


# ---- challenges and scoring -------------------------------------------
STYLE_NAMES = {"classic": "Standard: everything sharp",
               "portrait": "Portrait: Ana sharp, background blurred (hold SPACE)"}


def brief_text(part, want):
    n = PARTS[part]["name"]
    if PARTS[part]["expr_w"] < 0.5:
        return n
    return "%s - %s" % (n, EXPR_NAMES[want])


def reachable(part, ax):
    cx, cy, z = ideal_view(part, ax)
    return framing_score(part, ax, cx, cy, z) > 0.9


def make_shots(scene_id, seed=None, count=5, mood="neutral"):
    """The challenges of a scene: different parts/expressions/styles, each with its own timeline."""
    rng = random.Random(seed)
    sc = SCENES[scene_id]
    types = rng.sample(sc["shots"], min(count, len(sc["shots"])))
    portrait = set(rng.sample(range(len(types)), min(2, len(types))))
    shots = []
    for i, (part, want) in enumerate(types):
        shots.append({"scene": scene_id, "part": part, "want": want, "ax": sc["ax"],
                      "place": sc["place"], "room": sc["room"],
                      "style": "portrait" if i in portrait else "classic",
                      "brief": brief_text(part, want),
                      "imgs": dict(sc["images"]),
                      "still": sc["images"][want if PARTS[part]["expr_w"] > 0 else "neutral"],
                      "tl": None, "bl": None})
        shots[-1]["tl"], shots[-1]["bl"] = make_timeline(rng, mood, must=want if PARTS[part]["expr_w"] > 0 else None)
    return shots


def background_quality(style, bgb):
    if style == "portrait":
        return 0.35 + 0.65 * min(1.0, bgb / 0.85)
    return 1.0 - 0.6 * max(0.0, min(1.0, (bgb - 0.25) / 0.75))


def score_shot(shot, t, cx, cy, z, steady, bgb):
    """Score one photo: expression x framing x sharpness x background. Parts and total (0-100)."""
    ex = expression_score(shot["part"], shot["want"], t, shot["tl"], shot["bl"])
    fr = framing_score(shot["part"], shot["ax"], cx, cy, z)
    sh = max(0.0, min(1.0, steady))
    bq = background_quality(shot["style"], bgb)
    total = 100.0 * ex * (0.30 + 0.70 * fr) * (0.45 + 0.55 * sh) * bq
    return {"expr": int(round(ex * 100)), "framing": int(round(fr * 100)),
            "sharp": int(round(sh * 100)), "bg": int(round(bq * 100)), "total": int(round(total))}


def shot_tip(res, style="classic"):
    """One advice line about the weakest part of a shot."""
    worst = min(("expr", "framing", "sharp", "bg"), key=lambda k: res[k])
    if res[worst] >= 85:
        return "Excellent timing, framing, sharpness and background."
    bg_tip = ("Portrait shot: hold SPACE until the background blurs, then click."
              if style == "portrait" else "Standard shot: release SPACE so the background stays sharp.")
    return {"expr": "Wrong moment: watch her face and wait for the expression in the target (not mid-blink).",
            "framing": "Framing was off: match the target's zoom and position.",
            "sharp": "Camera shake: stop moving and let the picture settle before you click.",
            "bg": bg_tip}[worst]
